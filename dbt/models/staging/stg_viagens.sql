    pickup as embarque,
    dropoff as desembarque,
    vendorid as fornecedor,
    pulocationid as zona_origem,
    dolocationid as zona_destino,
    payment_type as pagamento,
    canal,
    passenger_count as passageiros,
    trip_distance as distancia_milhas,
    duracao_min,
    duracao_valida,
    velocidade_mph,
    fare_amount as tarifa_usd,
    tip_amount as gorjeta_usd,
    tolls_amount as pedagio_usd,
    coalesce(cbd_congestion_fee, 0) as taxa_cbd_usd,
    coalesce(airport_fee, 0) as taxa_aeroporto_usd,
    total_amount as total_usd,
    soma_confere,
    paga_taxa_cbd
